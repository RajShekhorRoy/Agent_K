import json
from agent.state import AgentState
from typing import List, Dict, Any

def build_planner_prompt(state: AgentState) -> str:
    """
    The LLM must output JSON ONLY.
    """
    schema = {
        "action": "one of: set_paths | run_antismash | run_pathway | list_outputs | read_file | multi | just_chat | set_bgc_id | display_bgc_antismash | get_pathway | show_pathway_details |",
        "args": {
            "genbank_path": "optional string",
            "antismash_dir": "optional string",
            "pathway_dir": "optional string",
            "output_dir": "optional string",
            "bgc_id": "optional string",
            "antismash_done": "optional boolean",
            "pathway_done": "optional boolean",
            "pathway_id": "optional string",
            "similarity": "optional number in [0,1]",
            "notes": "short explanation"
        },
        "notes": "short explanation",
    }

    state_view = {
        "genbank_path": state.genbank_path,
        "output_dir": state.output_dir,
        "antismash_dir": getattr(state, "antismash_dir", None),
        "pathway_dir": getattr(state, "pathway_dir", None),
        "antismash_done": state.antismash_done,
        "pathway_done": state.pathway_done,
        "pathway_id":  getattr(state, "pathway", None),
        "bgc_id": getattr(state, "bgc_id", None),
        "similarity":getattr(state, "similarity", None),
        "notes": "short explanation",
        }

    few_shots = (
        "Examples (follow the pattern exactly):\n"
        "User: show me the bgc for /DATA/A/Actinomyces with 0.40 similarity\n"
        "Assistant:\n"
        '{"action":"display_bgc_antismash","args":{"antismash_dir":"/DATA/A/Actinomyces","similarity":0.40},"notes":"Show BGCs with similarity >= 0.40"}\n\n'

        "User: list BGCs in /DATA/A/Actinomyces with similarity 0.4\n"
        "Assistant:\n"
        '{"action":"display_bgc_antismash","args":{"antismash_dir":"/DATA/A/Actinomyces","similarity":0.40},"notes":"show BGCs with similarity >= 0.40 "}\n\n'
 
        "User: show bgcs in /DATA/A/Actinomyces\n"
        "Assistant:\n"
        '{"action":"display_bgc_antismash","args":{"antismash_dir":"/DATA/A/Actinomyces","similarity":null},"notes":"No similarity filter requested"}\n\n'

        "User: set bgc_id to BGC0000888.5\n"
        "Assistant:\n"
        '{"action":"set_bgc_id","args":{"bgc_id":"BGC0000888.5"},"notes":"Set the current BGC id"}\n\n'
    )

    return (
        "You are the planner. Decide the next action.\n"
        "Return STRICT JSON ONLY. No markdown.\n\n"
        f"Current state:\n{json.dumps(state_view, indent=2)}\n\n"
        "Rules:\n"
        "- If user provides/mentions/shows interest in BGC or bgc or gene cluster of interest, choose set_bgc.\n"
        "- if the user mention some bgc_id set them, choose the action set_bgc_id"
        "- if the user mention set bgc_id set them, choose the action set_bgc_id"
        "- If the user mentions a specific bgc_id, BGC, gene cluster, region number, or cluster index  (e.g. BGC 2, region001, the NRPS cluster),choose the action set_bgc_id."
        "- If the user mentions a BGCor bgc_id ,choose the action set_bgc_id."
        "- Set BGC when bgc, bgc_id is mentioned, choose the action set_bgc_id"
        "- If the user mentions what are the pathway, choose the action get_pathway."
        "- pathway_id or pathway or pathway id or map or map_id are all the same thing"
        # "- If the user mentions what about the pathway details, choose the action show_pathway_details."
        "- If the user mentions about the product or details of pathway or details of product, choose the action show_pathway_details."
        "- If the user mentions or asks about possible pathway or pathway, choose the action get_pathway."
        "- If pathway_done is true, get_pathway should run without questions."
        "- If user provides/mentions genbank path or antismash dir or pathway dir or analysis dir, choose set_paths.\n"
        "- If the user explicitly states that antiSMASH has finished running (e.g., antismash is done, antismash completed, I already ran antismash),call the action `antismash_done`\n"
        "- If user asks to run antiSMASH, choose run_antismash.\n"
        "- Call `display_bgc_antismash` when the user explicitly asks to show,view or list BGCs generated by antiSMASH. Do NOT call it for explanations, definitions,or general questions about BGCs or antiSMASH.\n"
        "- When `display_bgc_antismash` is called, render the returned file to the user."
        "- If user asks pathway/product analysis, choose run_pathway.\n"
        "- If user asks what outputs exist, choose list_outputs.\n"
        "- run_antismash requires a GenBank file but if the user had already ran or completed it, then do no ask for it, just follow the instructions.\n"
        "- display_bgc_antismash does NOT require a GenBank file."
        "- display_bgc_antismash must execute immediately using antismash_dir and must NOT ask the user for genbank_path."
        "- If antismash_done is true, display_bgc_antismash should run without questions."
        "- If user asks about a specific result file, choose read_file with a relative path.\n"
        "- If multiple are needed, use action=multi with args.steps.\n\n"
        + few_shots
        +
        f"JSON schema:\n{json.dumps(schema, indent=2)}\n"
    )

